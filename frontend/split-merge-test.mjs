import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const BASE='http://localhost:8088'; const OUT='../screenshots'
const browser=await chromium.launch({channel:'chrome',headless:true})
const ctx=await browser.newContext({viewport:{width:1440,height:1000}})
const page=await ctx.newPage()
const errors=[]
page.on('console',m=>{if(m.type()==='error') errors.push(m.text())})
page.on('pageerror',e=>errors.push(e.message))
await page.goto(BASE+'/login',{waitUntil:'networkidle'})
await page.getByRole('button',{name:/审核人员/}).click()
await page.waitForURL('**/dashboard')
await page.goto(BASE+'/events',{waitUntil:'networkidle'})
await page.waitForTimeout(900)
const sourceRow=page.locator('.el-table__row').filter({hasText:'EV20261021231'}).first()
assert.ok(await sourceRow.count(), 'source event row missing')
await sourceRow.click()
await page.waitForTimeout(1000)
const checks=page.locator('.split-check')
console.log('split checks', await checks.count())
assert.ok(await checks.count()>0)
await checks.first().click()
await page.getByRole('button',{name:/拆分选中/}).click()
await page.waitForTimeout(1500)
const splitRow=page.locator('.el-table__row').filter({hasText:'拆分事件：'}).first()
console.log('split row', await splitRow.count())
assert.ok(await splitRow.count(), 'split event row missing')
await page.screenshot({path:OUT+'/35-e2e-split.png',fullPage:true})
await page.locator('.el-table__row').filter({hasText:'EV20261021231'}).first().locator('.el-checkbox').click()
await splitRow.locator('.el-checkbox').click()
await page.getByRole('button',{name:/合并选中/}).click()
await page.waitForTimeout(1500)
const body=await page.locator('body').innerText()
assert.ok(body.includes('事件已合并') || body.includes('2 条证据'))
await page.screenshot({path:OUT+'/36-e2e-merge.png',fullPage:true})
console.log('ERRORS',errors)
await browser.close()
